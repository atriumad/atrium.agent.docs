/**
 * Writes src/css/atrium-tokens.css from src/design/tokens.ts.
 *   bun scripts/build-tokens.ts           write the file
 *   bun scripts/build-tokens.ts --check   fail if the file is out of date (for CI)
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {
  brand, semantic, status, dataPalette, agentIdentity, fonts, typeRamp, tracking, space, radii,
  shadows, motion, zIndex, contrast, resolve,
} from '../src/design/tokens';

const out: string[] = [];
const decl = (name: string, value: string | number, comment?: string) =>
  out.push(`  --${name}: ${value};${comment ? ` /* ${comment} */` : ''}`);
const heading = (title: string) => out.push('', `  /* ---- ${title} ---- */`);

out.push(
  '/* GENERATED by scripts/build-tokens.ts from src/design/tokens.ts. Do not edit by hand.',
  ' * Atrium design tokens. Raw palette and type from the brand system; status colours, the data',
  ' * palette and the dark theme are the product layer. */',
  ':root {',
);

heading('Brand palette');
for (const group of Object.values(brand)) for (const s of group) decl(s.name, s.value, s.role.en);

heading('Semantic: surfaces, text, lines');
for (const group of Object.values(semantic)) for (const s of group) decl(s.name, s.value, s.role.en);
decl('accent', 'var(--mint-400)');
decl('accent-warm', 'var(--amber-500)');
decl('highlight', 'var(--amber-400)', 'the marker swipe behind a word');

heading('Semantic: status. Always with a word or an icon, never colour alone');
for (const s of status) {
  decl(`status-${s.key}-fg`, s.fg);
  decl(`status-${s.key}-bg`, s.bg);
  decl(`status-${s.key}-line`, s.line);
}

heading('Data palette, in the order series are used');
for (const s of dataPalette) decl(s.name, s.value);

heading('Agent identities');
for (const a of agentIdentity) {
  decl(`agent-${a.key}-head`, a.head);
  decl(`agent-${a.key}-eye`, a.eye);
  decl(`agent-${a.key}-bg`, a.bg);
  decl(`agent-${a.key}-fg`, a.fg);
}

heading('Focus. Two tones so it holds 3:1 on light and on dark');
decl('focus-ring', 'var(--teal-800)');
decl('focus-halo', 'rgba(247, 168, 35, 0.55)');

heading('Typography');
for (const f of fonts) decl(f.css.slice(2), f.stack);
decl('font-accent', 'var(--font-serif)');
decl('text-display-xl', 'clamp(3.5rem, 9vw, 7.5rem)');
decl('text-display-lg', 'clamp(2.75rem, 6vw, 5rem)');
decl('text-display-md', 'clamp(2.25rem, 4.5vw, 3.5rem)');
for (const t of typeRamp) decl(t.css.slice(2), `${t.px / 16}rem`, `${t.px}px`);
for (const w of [['light', 300], ['regular', 400], ['medium', 500], ['semibold', 600], ['bold', 700]] as const) {
  decl(`weight-${w[0]}`, w[1]);
}
for (const [n, v] of [['tight', 0.95], ['snug', 1.1], ['heading', 1.15], ['body', 1.6], ['relaxed', 1.75]] as const) {
  decl(`leading-${n}`, v);
}
for (const t of tracking) decl(t.css.slice(2), t.value);

heading('Spacing: an 8px grid with a 4px half step');
for (const s of space) decl(s.name, s.rem === 0 ? '0' : `${s.rem}rem`, s.rem === 0 ? undefined : `${s.rem * 16}px`);

heading('Shape');
for (const r of radii) decl(r.name, `${r.px}px`);
decl('radius-bento', '24px');
decl('radius-float', '18px');
decl('border-width', '1.5px', 'pills are drawn with a clean stroke');
decl('border-width-bold', '2px');
decl('container-max', '1200px');
decl('container-wide', '1360px');
decl('gutter', 'clamp(1.25rem, 4vw, 4rem)');

heading('Elevation: sparse. Colour does most of the work');
decl('shadow-none', 'none');
for (const s of shadows) decl(s.name, s.value);

heading('Motion');
decl('ease-out', 'cubic-bezier(0.16, 1, 0.3, 1)');
decl('ease-in-out', 'cubic-bezier(0.65, 0, 0.35, 1)');
for (const m of motion) decl(m.name, m.value);
decl('press-scale', '0.97');

heading('Layers');
for (const z of zIndex) decl(z.name, z.value);

out.push('}', '');

out.push(
  '/* Dark theme: the Manager chrome and any dark surface. Opt in with data-atr-theme="dark". */',
  '[data-atr-theme="dark"] {',
  '  --surface-page: var(--teal-900);',
  '  --surface-card: var(--teal-800);',
  '  --surface-sunken: var(--teal-700);',
  '  --text-strong: var(--mint-400);',
  '  --text-body: var(--cloud-300);',
  '  --text-muted: var(--teal-300);',
  '  --border-light: var(--teal-500);',
  '  --border-strong: var(--mint-400);',
  '  --focus-ring: var(--mint-400);',
  '  --status-positive-fg: #8fe6c2; --status-positive-bg: rgba(143, 230, 194, 0.12); --status-positive-line: rgba(143, 230, 194, 0.4);',
  '  --status-warning-fg: #ffc21f; --status-warning-bg: rgba(255, 194, 31, 0.12); --status-warning-line: rgba(255, 194, 31, 0.4);',
  '  --status-danger-fg: #f2a38c; --status-danger-bg: rgba(198, 91, 60, 0.18); --status-danger-line: rgba(242, 163, 140, 0.45);',
  '  --status-info-fg: #9dbcbe; --status-info-bg: rgba(157, 188, 190, 0.12); --status-info-line: rgba(157, 188, 190, 0.4);',
  '  --status-neutral-fg: var(--cloud-300); --status-neutral-bg: rgba(228, 238, 240, 0.08); --status-neutral-line: var(--teal-500);',
  '}',
  '',
  '@media (prefers-reduced-motion: reduce) {',
  '  :root { --dur-fast: 0ms; --dur-base: 0ms; --dur-slow: 0ms; --press-scale: 1; }',
  '}',
  '',
);

const css = out.join('\n');
const target = new URL('../src/css/atrium-tokens.css', import.meta.url);

// Guard rails: a token set that fails its own contrast rules should not ship.
const failures: string[] = [];
const need = (label: string, fg: string, bg: string, min: number) => {
  const ratio = contrast(resolve(fg), resolve(bg));
  if (ratio < min) failures.push(`${label}: ${ratio.toFixed(2)}:1 is below ${min}:1`);
};
need('text-strong on surface-page', 'var(--teal-800)', 'var(--cloud-200)', 7);
need('text-body on surface-card', 'var(--ink-700)', 'var(--cloud-100)', 7);
need('text-muted on surface-card', 'var(--teal-500)', 'var(--cloud-100)', 4.5);
need('text-muted on surface-sunken', 'var(--teal-500)', 'var(--cloud-300)', 4.5);
need('text-on-dark on surface-dark', 'var(--cloud-300)', 'var(--teal-800)', 7);
need('mint on surface-dark', 'var(--mint-400)', 'var(--teal-800)', 7);
need('teal on mint', 'var(--teal-800)', 'var(--mint-400)', 7);
need('teal on amber', 'var(--teal-800)', 'var(--amber-500)', 4.5);
for (const s of status) need(`status ${s.key} text on its tint`, s.fg, s.bg, 4.5);
if (failures.length) {
  console.error(failures.join('\n'));
  process.exit(1);
}

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) {
    console.error('src/css/atrium-tokens.css is out of date. Run: bun scripts/build-tokens.ts');
    process.exit(1);
  }
} else {
  writeFileSync(target, css);
  console.log(`wrote ${target.pathname} (${out.length} lines)`);
}
