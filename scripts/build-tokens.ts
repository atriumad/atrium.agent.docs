/**
 * Writes src/css/atrium-tokens.css from src/design/tokens.ts.
 *   bun scripts/build-tokens.ts           write the file
 *   bun scripts/build-tokens.ts --check   fail if the file is out of date (for CI)
 *
 * It also fails when a pairing the product relies on drops below its minimum contrast.
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {
  brand, semantic, status, dataPalette, fonts, typeRamp, tracking, space, radii, borders, shadows, motion,
  zIndex, contrast, resolve,
} from '../src/design/tokens';

const out: string[] = [];
const decl = (name: string, value: string | number, comment?: string) =>
  out.push(`  --${name}: ${value};${comment ? ` /* ${comment} */` : ''}`);
const heading = (title: string) => out.push('', `  /* ---- ${title} ---- */`);

out.push(
  '/* GENERATED by scripts/build-tokens.ts from src/design/tokens.ts. Do not edit by hand.',
  ' * Atrium tokens. The raw palette, type, space, radius, borders, shadows and motion are the',
  ' * ATRIUM AD design system\'s (design/system). Status, data and the dark theme are the product layer. */',
  ':root {',
);

heading('Raw palette');
for (const group of Object.values(brand)) for (const s of group) decl(s.name, s.value, s.role.en);

heading('Semantic: surfaces, text, lines');
for (const group of Object.values(semantic)) for (const s of group) decl(s.name, s.value, s.role.en);
decl('accent', 'var(--lime-500)');
decl('accent-warm', 'var(--clay-500)');
decl('highlight', 'var(--lime-500)', 'the flat marker block behind a word');
decl('field-border', 'var(--charcoal-500)', 'product: a field edge must clear 3:1; the cream hairline does not');

heading('Semantic: status. Fill, rule and mark, never hue alone');
for (const s of status) {
  decl(`status-${s.key}-fg`, s.fg);
  decl(`status-${s.key}-bg`, s.bg);
  decl(`status-${s.key}-line`, s.line);
}

heading('Data palette, in the order series are used');
for (const s of dataPalette) decl(s.name, s.value);

heading('Focus');
decl('focus-ring', 'var(--clay-500)');

heading('Typography');
for (const f of fonts) decl(f.css.slice(2), f.stack);
decl('font-display', 'var(--font-sans)');
decl('font-accent', 'var(--font-serif)');
decl('text-display-xl', 'clamp(3.25rem, 8.5vw, 7rem)');
decl('text-display-lg', 'clamp(2.5rem, 5.5vw, 4.5rem)');
decl('text-display-md', 'clamp(2rem, 4vw, 3.25rem)');
for (const t of typeRamp) decl(t.css.slice(2), `${t.px / 16}rem`, `${t.px}px`);
for (const w of [['light', 300], ['regular', 400], ['medium', 500], ['semibold', 600], ['bold', 700]] as const) {
  decl(`weight-${w[0]}`, w[1], w[1] > 500 ? 'not used by the system' : undefined);
}
for (const [n, v] of [['tight', 0.92], ['snug', 1.05], ['heading', 1.15], ['body', 1.6], ['relaxed', 1.75]] as const) {
  decl(`leading-${n}`, v);
}
for (const t of tracking) decl(t.css.slice(2), t.value);

heading('Spacing: a 4px grid');
for (const s of space) decl(s.name, s.rem === 0 ? '0' : `${s.rem}rem`, s.rem === 0 ? undefined : `${s.rem * 16}px`);

heading('Shape: squared-off. Chips alone go round');
for (const r of radii) decl(r.name, r.px === 0 ? '0' : `${r.px}px`);
for (const b of borders) decl(b.name, b.value);
decl('container-max', '1240px');
decl('container-wide', '1440px');
decl('container-text', '68ch');
decl('gutter', 'clamp(1.25rem, 4vw, 3.5rem)');

heading('Elevation: drawn, not shaded');
decl('shadow-none', 'none');
for (const s of shadows) decl(s.name, s.value);

heading('Motion');
decl('ease-out', 'cubic-bezier(0.2, 0.8, 0.2, 1)');
decl('ease-in-out', 'cubic-bezier(0.65, 0, 0.35, 1)');
for (const m of motion) decl(m.name, m.value);
decl('press-shift', '1px');

heading('Layers');
for (const z of zIndex) decl(z.name, z.value);

out.push('}', '');

out.push(
  '/* Dark theme: any charcoal field, and the Manager chrome. Opt in with data-atr-theme="dark". */',
  '[data-atr-theme="dark"] {',
  '  --surface-page: var(--charcoal-900);',
  '  --surface-card: var(--charcoal-800);',
  '  --surface-sunken: var(--charcoal-700);',
  '  --text-strong: var(--cream-100);',
  '  --text-body: var(--cream-300);',
  '  --text-muted: var(--charcoal-400);',
  '  --border-light: var(--charcoal-500);',
  '  --border-strong: var(--cream-300);',
  '  --rule: var(--cream-300);',
  '  --field-border: var(--charcoal-400);',
  '  --status-positive-fg: var(--lime-500); --status-positive-bg: rgba(198, 242, 78, 0.10); --status-positive-line: var(--lime-500);',
  '  --status-warning-fg: var(--cream-200); --status-warning-bg: rgba(228, 226, 209, 0.08); --status-warning-line: var(--clay-500);',
  '  --status-danger-fg: var(--clay-300); --status-danger-bg: rgba(217, 84, 43, 0.18); --status-danger-line: var(--clay-500);',
  '  --status-info-fg: var(--cream-400); --status-info-bg: rgba(212, 202, 182, 0.08); --status-info-line: var(--charcoal-500);',
  '  --status-neutral-fg: var(--cream-400); --status-neutral-bg: transparent; --status-neutral-line: var(--charcoal-500);',
  '}',
  '',
  '@media (prefers-reduced-motion: reduce) {',
  '  :root { --dur-fast: 0ms; --dur-base: 0ms; --dur-slow: 0ms; --press-shift: 0px; }',
  '}',
  '',
);

const css = out.join('\n');
const target = new URL('../src/css/atrium-tokens.css', import.meta.url);

/* Guard rails. These are the pairings the product relies on. The system's own pairings that
 * fall short (cream on clay-500, lime-600 text, a cream hairline as a field edge) are listed in
 * the accessibility page with the rule that avoids them, and are not used by any component. */
const failures: string[] = [];
const need = (label: string, fg: string, bg: string, min: number) => {
  const ratio = contrast(resolve(fg), resolve(bg));
  if (ratio < min) failures.push(`${label}: ${ratio.toFixed(2)}:1 is below ${min}:1`);
};
need('text-strong on surface-page', 'var(--charcoal-900)', 'var(--cream-200)', 7);
need('text-body on surface-card', 'var(--charcoal-800)', 'var(--cream-100)', 7);
need('text-muted on surface-page', 'var(--charcoal-500)', 'var(--cream-200)', 4.5);
need('text-muted on surface-card', 'var(--charcoal-500)', 'var(--cream-100)', 4.5);
need('text-muted on surface-sunken', 'var(--charcoal-500)', 'var(--cream-300)', 4.5);
need('text-on-dark on surface-dark', 'var(--cream-300)', 'var(--charcoal-800)', 7);
need('lime on surface-dark', 'var(--lime-500)', 'var(--charcoal-800)', 7);
need('hint on dark: charcoal-400 on charcoal-800', 'var(--charcoal-400)', 'var(--charcoal-800)', 4.5);
need('text on lime', 'var(--charcoal-900)', 'var(--lime-500)', 7);
need('primary button', 'var(--cream-200)', 'var(--charcoal-800)', 7);
need('clay button: cream on clay-600', 'var(--cream-100)', 'var(--clay-600)', 4.5);
need('clay button pressed: cream on clay-700', 'var(--cream-100)', 'var(--clay-700)', 4.5);
need('clay chip: clay-700 on clay-200', 'var(--clay-700)', 'var(--clay-200)', 4.5);
need('error text: clay-600 on cream-100', 'var(--clay-600)', 'var(--cream-100)', 4.5);
need('field edge: charcoal-500 on cream-100', 'var(--charcoal-500)', 'var(--cream-100)', 3);
need('field edge on dark: charcoal-400 on charcoal-800', 'var(--charcoal-400)', 'var(--charcoal-800)', 3);
need('focus ring: clay-500 on cream-200', 'var(--clay-500)', 'var(--cream-200)', 3);
need('focus ring: clay-500 on charcoal-800', 'var(--clay-500)', 'var(--charcoal-800)', 3);
for (const s of status) need(`status ${s.key}: text on its fill`, s.fg, s.bg, 4.5);
if (failures.length) {
  console.error(failures.join('\n'));
  process.exit(1);
}

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== css) {
    console.error('src/css/atrium-tokens.css is out of date. Run: bun scripts/build-tokens.ts');
    process.exit(1);
  }
} else {
  writeFileSync(target, css);
  console.log(`wrote ${target.pathname} (${out.length} lines)`);
}
